import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import ts from 'typescript';

// Keep the authoritative D1 declarations, without introducing Worker globals
// into the shared browser/server TypeScript program (notably Request/Response).
const names = new Set([
  'D1Meta', 'D1Response', 'D1Result', 'D1ExecResult',
  'D1SessionConstraint', 'D1SessionBookmark', 'D1Database',
  'D1DatabaseSession', 'D1PreparedStatement',
]);
const directory = mkdtempSync(join(tmpdir(), 'lob-binding-types-'));
try {
  const generated = join(directory, 'worker-runtime.d.ts');
  execFileSync(process.execPath, [
    'node_modules/wrangler/bin/wrangler.js', 'types', generated,
    '--config', 'types/wrangler-types.jsonc', '--include-env=false',
  ], {
    stdio: 'inherit',
    env: { ...process.env, WRANGLER_SEND_METRICS: 'false' },
  });
  const source = readFileSync(generated, 'utf8');
  const file = ts.createSourceFile(generated, source, ts.ScriptTarget.Latest, true);
  const declarations = file.statements.filter(statement =>
    statement.name && names.has(statement.name.text));
  if (declarations.length !== names.size) {
    throw new Error('Wrangler D1 declarations changed; review before regenerating.');
  }
  const copyright = source.match(/\/\*! \*+[\s\S]*?\*\//)?.[0];
  const provenance = source.match(/^\/\/ Runtime types generated.*$/m)?.[0];
  if (!copyright || !provenance) {
    throw new Error('Missing Wrangler runtime provenance or license.');
  }
  const output = [
    '// Generated by npm run types:generate. Do not edit by hand.',
    provenance,
    copyright,
    '// Module-scoped D1 bindings only; retain lib.dom for browser/server APIs.',
    ...declarations.map(statement => statement.getFullText(file).trim()),
    `export type { ${[...names].join(', ')} };`,
    '',
  ].join('\n\n');
  writeFileSync('types/cloudflare-d1.d.ts', output.split('\n').map(line=>line.trimEnd()).join('\n').trimEnd()+'\n');
} finally {
  rmSync(directory, { recursive: true, force: true });
}
